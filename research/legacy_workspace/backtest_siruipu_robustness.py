#!/usr/bin/env python3
"""右侧趋势公式稳健性回测：同期基准、年度分层、HAC、成本和可执行组合。

信号沿用 backtest_siruipu_right_side.py 的无未来函数事件表；本脚本只计算
信号后的结果。组合规则：空仓时取当日 RPS120 前10个可执行信号，次日开盘
等权买入，第10个交易日收盘全部卖出；持有期间不新增，随后等待下一信号。
"""
from __future__ import annotations

import argparse
import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "output"
RAW = OUT / "tdx_stock_daily_with_rps.parquet"
VARIANTS = ["V1_DISCOVERY", "V2_FINAL", "V2_PRIORITY"]
HORIZONS = [5, 10, 20]
COSTS = [0.002, 0.005, 0.010]
TRAIN_END = pd.Timestamp("2024-12-31")


def hac_tstat(values: pd.Series, lag: int) -> float | None:
    x = values.dropna().to_numpy(float)
    n = len(x)
    if n < max(20, lag + 3):
        return None
    u = x - x.mean()
    gamma0 = float(np.dot(u, u) / n)
    long_var = gamma0
    for k in range(1, min(lag, n - 1) + 1):
        gamma = float(np.dot(u[k:], u[:-k]) / n)
        weight = 1.0 - k / (lag + 1.0)
        long_var += 2.0 * weight * gamma
    if long_var <= 0:
        return None
    se = np.sqrt(long_var / n)
    return float(x.mean() / se) if se else None


def max_drawdown(returns: pd.Series) -> float | None:
    s = returns.dropna().astype(float)
    if s.empty:
        return None
    equity = (1.0 + s).cumprod()
    dd = equity / equity.cummax() - 1.0
    return float(dd.min())


def portfolio_sim(frame: pd.DataFrame, horizon: int = 10, cost: float = 0.002) -> dict:
    f = frame[frame["executable"] & frame[f"ret{horizon}_gross"].notna()].copy()
    f = f.sort_values(["trade_date", "RPS_120", "RPS_250"], ascending=[True, False, False])
    dates = sorted(f["trade_date"].drop_duplicates())
    rows = []
    next_allowed = pd.Timestamp.min
    for date in dates:
        if date < next_allowed:
            continue
        picks = f[f["trade_date"] == date].head(10)
        if picks.empty:
            continue
        exit_dates = picks["trade_date"].map(lambda d: d)
        gross = float(picks[f"ret{horizon}_gross"].mean())
        bench = float(picks[f"bench{horizon}_gross"].mean())
        # 下一次允许信号日期：当前交易日后 horizon 个全市场交易日。
        exit_date = picks[f"exit_date_{horizon}"].dropna().max()
        if pd.isna(exit_date):
            continue
        next_allowed = pd.Timestamp(exit_date) + pd.Timedelta(nanoseconds=1)
        rows.append({
            "signal_date": date, "exit_date": pd.Timestamp(exit_date),
            "n_stocks": int(len(picks)), "gross": gross,
            "net": gross - cost, "benchmark": bench - cost,
            "excess": gross - bench,
        })
    p = pd.DataFrame(rows)
    if p.empty:
        return {"cohorts": 0}
    total = float((1 + p["net"]).prod() - 1)
    bench_total = float((1 + p["benchmark"]).prod() - 1)
    years = max((p["exit_date"].max() - p["signal_date"].min()).days / 365.25, 1 / 365.25)
    cagr = float((1 + total) ** (1 / years) - 1) if total > -1 else -1.0
    bench_cagr = float((1 + bench_total) ** (1 / years) - 1) if bench_total > -1 else -1.0
    return {
        "cohorts": int(len(p)), "mean_stocks": float(p["n_stocks"].mean()),
        "total_return": total, "cagr": cagr, "max_drawdown": max_drawdown(p["net"]),
        "win_rate": float((p["net"] > 0).mean()), "mean_trade": float(p["net"].mean()),
        "median_trade": float(p["net"].median()),
        "benchmark_total": bench_total, "benchmark_cagr": bench_cagr,
        "mean_excess": float(p["excess"].mean()),
        "first_signal": p["signal_date"].min().strftime("%Y-%m-%d"),
        "last_exit": p["exit_date"].max().strftime("%Y-%m-%d"),
        "rows": p,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--events", required=True, help="backtest event parquet generated by backtest_siruipu_right_side.py")
    args = ap.parse_args()
    events_path = Path(args.events).resolve()

    events = pd.read_parquet(events_path)
    events["trade_date"] = pd.to_datetime(events["trade_date"])
    events = events[events["variant"].isin(VARIANTS)].copy()

    cols = ["trade_date", "ts_code", "open", "close", "RPS_250"]
    raw = pd.read_parquet(RAW, columns=cols, filters=[("trade_date", ">=", pd.Timestamp("2020-01-01"))])
    raw["trade_date"] = pd.to_datetime(raw["trade_date"])
    raw = raw.sort_values(["ts_code", "trade_date"])
    calendars = raw["trade_date"].drop_duplicates().sort_values().reset_index(drop=True)
    calendar_pos = pd.Series(calendars.index.to_numpy(), index=calendars).to_dict()

    # 严格使用全市场交易日历。旧事件表的 shift(-1) 是“该股票下一根K线”，
    # 停牌时不等于下一市场交易日，因此这里重算入场、退出和可执行性。
    events["_legacy_executable"] = events["executable"].astype(bool)
    events["entry_date"] = events["trade_date"].map(
        lambda d: calendars.iloc[calendar_pos[d] + 1] if d in calendar_pos and calendar_pos[d] + 1 < len(calendars) else pd.NaT
    )
    entry_lookup = raw[["trade_date", "ts_code", "open"]].rename(
        columns={"trade_date": "entry_date", "open": "entry_open_aligned"}
    )
    events = events.drop(columns=["entry_open", "entry_gap", "executable"], errors="ignore").merge(
        entry_lookup, on=["entry_date", "ts_code"], how="left", validate="many_to_one"
    )
    events["entry_gap_aligned"] = events["entry_open_aligned"] / events["close"] - 1.0
    limit = np.where(events["ts_code"].str[:3].isin(["300", "301", "688", "689"]), 0.20, 0.10)
    events["executable"] = events["entry_open_aligned"].notna() & (events["entry_gap_aligned"] < limit - 0.005)

    open_panel = raw.pivot(index="trade_date", columns="ts_code", values="open").reindex(calendars)
    close_panel = raw.pivot(index="trade_date", columns="ts_code", values="close").reindex(calendars)
    ready_panel = raw.assign(ready=raw["RPS_250"].notna()).pivot(
        index="trade_date", columns="ts_code", values="ready"
    ).reindex(calendars).fillna(False)

    close_lookup = raw[["trade_date", "ts_code", "close"]]

    for h in HORIZONS:
        event_exit = events["trade_date"].map(
            lambda d: calendars.iloc[calendar_pos[d] + h] if d in calendar_pos and calendar_pos[d] + h < len(calendars) else pd.NaT
        )
        events[f"exit_date_{h}"] = event_exit
        exit_lookup = close_lookup.rename(
            columns={"trade_date": f"exit_date_{h}", "close": f"exit_close_{h}"}
        )
        events = events.merge(exit_lookup, on=[f"exit_date_{h}", "ts_code"], how="left", validate="many_to_one")
        events[f"ret{h}_gross"] = events[f"exit_close_{h}"] / events["entry_open_aligned"] - 1.0
        events[f"ret{h}_net"] = events[f"ret{h}_gross"] - 0.002

        bench_values = {}
        for i in range(0, len(calendars) - h):
            denom = open_panel.iloc[i + 1]
            numer = close_panel.iloc[i + h]
            valid = ready_panel.iloc[i] & denom.notna() & numer.notna()
            if valid.any():
                bench_values[calendars.iloc[i]] = float((numer[valid] / denom[valid] - 1.0).mean())
        events[f"bench{h}_gross"] = events["trade_date"].map(bench_values)

    daily_rows = []
    for variant in VARIANTS:
        v = events[(events["variant"] == variant) & events["executable"]].copy()
        for split, subset in {
            "TRAIN": v[v["trade_date"] <= TRAIN_END],
            "TEST": v[v["trade_date"] > TRAIN_END],
            "ALL": v,
        }.items():
            for h in HORIZONS:
                x = subset.dropna(subset=[f"ret{h}_gross", f"bench{h}_gross"]).copy()
                if x.empty:
                    continue
                d = x.groupby("trade_date", as_index=False).agg(
                    n=("ts_code", "size"),
                    gross=(f"ret{h}_gross", "mean"),
                    benchmark=(f"bench{h}_gross", "mean"),
                )
                d["net"] = d["gross"] - 0.002
                d["excess"] = d["gross"] - d["benchmark"]
                daily_rows.extend({
                    "split": split, "variant": variant, "horizon": h,
                    "trade_date": row.trade_date, "n": int(row.n),
                    "gross": float(row.gross), "net": float(row.net),
                    "benchmark": float(row.benchmark), "excess": float(row.excess),
                } for row in d.itertuples(index=False))
    daily = pd.DataFrame(daily_rows)

    summary = []
    for keys, d in daily.groupby(["split", "variant", "horizon"]):
        split, variant, h = keys
        summary.append({
            "split": split, "variant": variant, "horizon": int(h),
            "signal_dates": int(len(d)), "events": int(d["n"].sum()),
            "mean_daily_cohort_net": float(d["net"].mean()),
            "median_daily_cohort_net": float(d["net"].median()),
            "positive_cohort_rate": float((d["net"] > 0).mean()),
            "mean_excess": float(d["excess"].mean()),
            "positive_excess_rate": float((d["excess"] > 0).mean()),
            "hac_t_net": hac_tstat(d["net"], int(h)),
            "hac_t_excess": hac_tstat(d["excess"], int(h)),
        })

    annual = []
    for (variant, h, year), d in daily[daily["split"] == "ALL"].assign(
        year=lambda x: x["trade_date"].dt.year
    ).groupby(["variant", "horizon", "year"]):
        annual.append({
            "variant": variant, "horizon": int(h), "year": int(year),
            "signal_dates": int(len(d)), "events": int(d["n"].sum()),
            "mean_net": float(d["net"].mean()), "median_net": float(d["net"].median()),
            "mean_excess": float(d["excess"].mean()),
            "positive_rate": float((d["net"] > 0).mean()),
        })

    stage_summary = []
    exact_events = events[(events["variant"] == "V1_DISCOVERY") & events["executable"]].copy()
    for split, subset in {
        "TRAIN": exact_events[exact_events["trade_date"] <= TRAIN_END],
        "TEST": exact_events[exact_events["trade_date"] > TRAIN_END],
        "ALL": exact_events,
    }.items():
        for stage, s0 in subset.groupby("stage"):
            for h in HORIZONS:
                s = s0.dropna(subset=[f"ret{h}_gross", f"bench{h}_gross"])
                if s.empty:
                    continue
                d = s.groupby("trade_date", as_index=False).agg(
                    n=("ts_code", "size"), gross=(f"ret{h}_gross", "mean"),
                    benchmark=(f"bench{h}_gross", "mean"),
                )
                net = d["gross"] - 0.002
                excess = d["gross"] - d["benchmark"]
                stage_summary.append({
                    "split": split, "stage": stage, "horizon": h,
                    "signal_dates": int(len(d)), "events": int(d["n"].sum()),
                    "mean_net": float(net.mean()), "median_net": float(net.median()),
                    "positive_rate": float((net > 0).mean()),
                    "mean_excess": float(excess.mean()),
                    "hac_t_net": hac_tstat(net, h), "hac_t_excess": hac_tstat(excess, h),
                })

    sensitivity = []
    portfolios = []
    portfolio_rows = []
    for split, predicate in {
        "TRAIN": events["trade_date"] <= TRAIN_END,
        "TEST": events["trade_date"] > TRAIN_END,
        "ALL": pd.Series(True, index=events.index),
    }.items():
        for variant in VARIANTS:
            frame = events[predicate & (events["variant"] == variant)].copy()
            for cost in COSTS:
                sim = portfolio_sim(frame, 10, cost)
                row_df = sim.pop("rows", None)
                record = {"split": split, "variant": variant, "horizon": 10, "cost": cost, **sim}
                portfolios.append(record)
                if row_df is not None and cost == 0.002:
                    row_df = row_df.copy()
                    row_df["split"] = split
                    row_df["variant"] = variant
                    portfolio_rows.append(row_df)
            # 事件成本敏感性，按信号日等权。
            d0 = daily[(daily["split"] == split) & (daily["variant"] == variant) & (daily["horizon"] == 10)]
            for cost in COSTS:
                sensitivity.append({
                    "split": split, "variant": variant, "horizon": 10, "cost": cost,
                    "mean_daily_cohort_net": None if d0.empty else float((d0["gross"] - cost).mean()),
                    "positive_rate": None if d0.empty else float(((d0["gross"] - cost) > 0).mean()),
                })

    tag = events["trade_date"].max().strftime("%Y%m%d")
    daily_path = OUT / f"siruipu_robust_daily_cohorts_{tag}.csv"
    portfolio_path = OUT / f"siruipu_robust_portfolio_cohorts_{tag}.csv"
    json_path = OUT / f"siruipu_robust_backtest_{tag}.json"
    daily.to_csv(daily_path, index=False, encoding="utf-8-sig")
    if portfolio_rows:
        pd.concat(portfolio_rows, ignore_index=True).to_csv(portfolio_path, index=False, encoding="utf-8-sig")
    payload = {
        "generated_at": datetime.now(timezone(timedelta(hours=8))).strftime("%Y-%m-%d %H:%M:%S"),
        "source": str(RAW.as_posix()), "events": str(events_path.as_posix()),
        "window": [events["trade_date"].min().strftime("%Y-%m-%d"), events["trade_date"].max().strftime("%Y-%m-%d")],
        "train_end": TRAIN_END.strftime("%Y-%m-%d"),
        "benchmark": "same signal date, equal-weight mean return of all Shanghai/Shenzhen A-shares with RPS250 available; same next-open to horizon-close window",
        "daily_cohort": "all executable events on the same signal date are equal-weighted; HAC lag equals holding horizon",
        "portfolio_rule": "when flat, take top 10 signals by RPS120 then RPS250; enter next open; equal weight; exit at day-10 close; ignore signals while holding",
        "costs": COSTS,
        "execution_alignment": {
            "legacy_event_rows_executable": int(events["_legacy_executable"].sum()),
            "calendar_aligned_event_rows_executable": int(events["executable"].sum()),
            "legacy_executable_but_no_next_market_day_open": int((events["_legacy_executable"] & events["entry_open_aligned"].isna()).sum()),
        },
        "summary": summary, "annual": annual, "stage_summary": stage_summary,
        "cost_sensitivity": sensitivity,
        "portfolios": portfolios,
        "limitations": [
            "Historical ST name state is unavailable; event source does not exclude historical ST stocks.",
            "V2 thresholds were created after observing part of the history; the TEST label is a time split, not a truly untouched prospective sample.",
            "No intraday path, bid/ask queue, suspension queue or limit-up order-fill simulation beyond the next-open gap filter.",
            "Equal-weight benchmark is a research baseline, not a tradable index total-return series.",
            "Hithink qfq research view is separate from the project G0 Tencent reconciliation, which is currently failed.",
        ],
        "daily_csv": str(daily_path.as_posix()),
        "portfolio_csv": str(portfolio_path.as_posix()),
    }
    json_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"json": str(json_path), "daily": str(daily_path), "portfolio": str(portfolio_path)}, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
